export function getPresetBySlug(slug: string): RatePreset | undefined {
  return RATE_PRESETS.find((p) => p.slug === slug);
}

export function buildQuoteFromPreset(
  preset: RatePreset,
  existingBrand?: QuoteDocument["brand"]
): QuoteDocument {
  const today = new Date();
  const plusDays = (days: number) => {
    const d = new Date(today);
    d.setDate(d.getDate() + days);
    return d.toISOString().slice(0, 10);
  };

  return {
    id: `qt-${Date.now()}`,
    presetSlug: preset.slug,
    quoteNumber: `QT-2026-${String(RATE_PRESETS.indexOf(preset) + 101)}`,
    projectTitle: preset.projectTitle,
    summary: preset.summary,
    issueDate: plusDays(0),
    validUntil: plusDays(14),
    currency: "USD",
    providerName: "Northstar Digital Studio LLC",
    providerContact: "Alex Mercer, Principal",
    providerEmail: "hello@northstardigital.co",
    clientCompany: "Acme Commerce Inc.",
    clientContact: "Jordan Vance, VP Operations",
    inputs: { ...preset.defaultInputs },
    tiers: [
      { ...preset.tiers[0], deliverables: [...preset.tiers[0].deliverables] },
      { ...preset.tiers[1], deliverables: [...preset.tiers[1].deliverables] },
      { ...preset.tiers[2], deliverables: [...preset.tiers[2].deliverables] },
    ],
    brand: existingBrand ?? {
      accentColor: "#1D4ED8",
      logoDataUrl: "",
      customFooter: "",
    },
  };
}
