function makeInputs(
  hours: number,
  hourly: number,
  complexity: PricingInputs["complexity"] = "moderate",
  expenses = 0
): PricingInputs {
  return {
    estimatedHours: hours,
    hourlyBaseline: hourly,
    complexity,
    adminBufferPercent: 18,
    directExpenses: expenses,
    desiredMarginPercent: 25,
    valueMultiplier: 1.15,
  };
}

