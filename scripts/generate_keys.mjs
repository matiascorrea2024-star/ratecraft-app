import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const ALPHABET = "ABCDEFGHJKMNPQRSTVWXYZ23456789";
const SALT = "ratecraft-craftapp-studio-2026-v1";
const KEY_COUNT = 500;

function computeChecksumChar(body11) {
  let sum = 0;
  for (let i = 0; i < body11.length; i++) {
    sum = (sum * 31 + body11.charCodeAt(i)) % ALPHABET.length;
  }
  return ALPHABET[sum];
}

function generateCandidateKey() {
  const bytes = crypto.randomBytes(11);
  let body = "";
  for (let i = 0; i < 11; i++) {
    body += ALPHABET[bytes[i] % ALPHABET.length];
  }
  const full12 = body + computeChecksumChar(body);
  return `RC-PRO-${full12.slice(0, 4)}-${full12.slice(4, 8)}-${full12.slice(8, 12)}`;
}

function hashKey(key) {
  return crypto
    .createHash("sha256")
    .update(`${SALT}:${key}`)
    .digest("hex")
    .slice(0, 20);
}

const keys = new Set();
const hashes = [];
while (keys.size < KEY_COUNT) {
  const key = generateCandidateKey();
  if (!keys.has(key)) {
    keys.add(key);
    hashes.push(hashKey(key));
  }
}

const rootDir = process.cwd();
fs.mkdirSync(path.join(rootDir, "launch_kit"), { recursive: true });
fs.mkdirSync(path.join(rootDir, "src", "lib"), { recursive: true });

const keysList = Array.from(keys);
fs.writeFileSync(
  path.join(rootDir, "launch_kit", "license_keys_500.txt"),
  keysList.join("\n") + "\n",
  "utf8"
);

const tsContent = `// Auto-generated by scripts/generate_keys.mjs — irreversible salted SHA-256 prefixes.
export const LICENSE_HASH_SALT = "${SALT}";

export const VALID_LICENSE_HASHES: ReadonlySet<string> = new Set([
${hashes.map((h) => `  "${h}",`).join("\n")}
]);
`;
fs.writeFileSync(path.join(rootDir, "src", "lib", "licenseHashes.ts"), tsContent, "utf8");
console.log(`Generated ${keysList.length} unique RateCraft Pro keys.`);
